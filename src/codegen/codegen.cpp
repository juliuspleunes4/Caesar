std::string CCodeGenerator::indent() const {
    return std::string(indent_level * 4, ' ');
}

void CCodeGenerator::emitLine(const std::string& line) {
    output << indent() << line << "\n";
}

void CCodeGenerator::emitInstruction(const IRInstruction& instr) {
    switch (instr.opcode) {
        case IROpcode::LOAD_CONST:
            // Check if it's a string literal (starts with ")
            if (!instr.src1.value.empty() && instr.src1.value[0] == '"') {
                emitLine("const char* " + instr.dest.value + " = " + instr.src1.value + ";");
                register_types[instr.dest.value] = "const char*";
            } else if (instr.src1.value.find('.') != std::string::npos || 
                       instr.src1.value.find('e') != std::string::npos ||
                       instr.src1.value.find('E') != std::string::npos) {
                // Float literal (contains . or scientific notation)
                emitLine("double " + instr.dest.value + " = " + instr.src1.value + ";");
                register_types[instr.dest.value] = "double";
            } else {
                emitLine("int64_t " + instr.dest.value + " = " + instr.src1.value + ";");
                register_types[instr.dest.value] = "int64_t";
            }
            break;
            
        case IROpcode::GET_VAR: {
            // Get type from variable if known
            auto vit = variable_types.find(instr.src1.value);
            std::string var_type = (vit != variable_types.end()) ? vit->second : "int64_t";
            emitLine(var_type + " " + instr.dest.value + " = " + instr.src1.value + ";");
            register_types[instr.dest.value] = var_type;
            break;
        }
            
        case IROpcode::SET_VAR: {
            emitLine(instr.dest.value + " = " + instr.src1.value + ";");
            // Track variable type from source register
            auto it = register_types.find(instr.src1.value);
            if (it != register_types.end()) {
                variable_types[instr.dest.value] = it->second;
            }
            break;
        }
            
        case IROpcode::ADD: {
            // Determine result type: if either operand is double, result is double
            std::string type1 = register_types.count(instr.src1.value) ? register_types[instr.src1.value] : "int64_t";
            std::string type2 = register_types.count(instr.src2.value) ? register_types[instr.src2.value] : "int64_t";
            std::string result_type = (type1 == "double" || type2 == "double") ? "double" : "int64_t";
            emitLine(result_type + " " + instr.dest.value + " = " + instr.src1.value + " + " + instr.src2.value + ";");
            register_types[instr.dest.value] = result_type;
            break;
        }
            
        case IROpcode::SUB: {
            std::string type1 = register_types.count(instr.src1.value) ? register_types[instr.src1.value] : "int64_t";
            std::string type2 = register_types.count(instr.src2.value) ? register_types[instr.src2.value] : "int64_t";
            std::string result_type = (type1 == "double" || type2 == "double") ? "double" : "int64_t";
            emitLine(result_type + " " + instr.dest.value + " = " + instr.src1.value + " - " + instr.src2.value + ";");
            register_types[instr.dest.value] = result_type;
            break;
        }
            
        case IROpcode::MUL: {
            std::string type1 = register_types.count(instr.src1.value) ? register_types[instr.src1.value] : "int64_t";
            std::string type2 = register_types.count(instr.src2.value) ? register_types[instr.src2.value] : "int64_t";
            std::string result_type = (type1 == "double" || type2 == "double") ? "double" : "int64_t";
            emitLine(result_type + " " + instr.dest.value + " = " + instr.src1.value + " * " + instr.src2.value + ";");
            register_types[instr.dest.value] = result_type;
            break;
        }
            
        case IROpcode::DIV: {
            // Division always returns double for proper mathematical behavior
            std::string type1 = register_types.count(instr.src1.value) ? register_types[instr.src1.value] : "int64_t";
            std::string type2 = register_types.count(instr.src2.value) ? register_types[instr.src2.value] : "int64_t";
            // Cast to double if necessary
            std::string left = (type1 == "double") ? instr.src1.value : "(double)" + instr.src1.value;
            std::string right = (type2 == "double") ? instr.src2.value : "(double)" + instr.src2.value;
            emitLine("double " + instr.dest.value + " = " + left + " / " + right + ";");
            register_types[instr.dest.value] = "double";
            break;
        }
            
        case IROpcode::MOD:
            emitLine("int64_t " + instr.dest.value + " = " + instr.src1.value + " % " + instr.src2.value + ";");
            break;
            
        case IROpcode::NEG: {
            std::string type1 = register_types.count(instr.src1.value) ? register_types[instr.src1.value] : "int64_t";
            emitLine(type1 + " " + instr.dest.value + " = -" + instr.src1.value + ";");
            register_types[instr.dest.value] = type1;
            break;
        }
            break;
            
        case IROpcode::EQ:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " == " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::NE:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " != " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::LT:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " < " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::LE:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " <= " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::GT:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " > " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::GE:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " >= " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::AND:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " && " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::OR:
            emitLine("bool " + instr.dest.value + " = " + instr.src1.value + " || " + instr.src2.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::NOT:
            emitLine("bool " + instr.dest.value + " = !" + instr.src1.value + ";");
            register_types[instr.dest.value] = "bool";
            break;
            
        case IROpcode::JUMP:
            emitLine("goto " + instr.dest.value + ";");
            break;
            
        case IROpcode::JUMP_IF_FALSE:
            emitLine("if (!" + instr.src1.value + ") goto " + instr.dest.value + ";");
            break;
            
        case IROpcode::RETURN:
            if (instr.dest.type != IROperandType::NONE) {
                emitLine("return " + instr.dest.value + ";");
            } else {
                emitLine("return 0;");
            }
            break;
            
        case IROpcode::PARAM:
            // Store parameter for next CALL
            call_params.push_back(instr.dest.value);
            break;
            
        case IROpcode::CALL: {
            // Handle built-in functions
            if (instr.src1.value == "print") {
                if (!call_params.empty()) {
                    std::string param = call_params.back();  // Take last parameter
                    // Check register type
                    auto it = register_types.find(param);
                    if (it != register_types.end()) {
                        if (it->second == "char*" || it->second == "const char*") {
                            emitLine("caesar_print_str(" + param + ");");
                        } else if (it->second == "double") {
                            emitLine("caesar_print_double(" + param + ");");
                        } else {
                            emitLine("caesar_print_int(" + param + ");");
                        }
                    } else {
                        emitLine("caesar_print_int(" + param + ");");
                    }
                    call_params.pop_back();  // Remove used parameter
                }
            } else if (instr.src1.value == "range") {
                // range() returns a CaesarRange iterator
                size_t num_params = call_params.size();
                if (num_params >= 3) {
                    size_t start_idx = num_params - 3;
                    emitLine("CaesarRange " + instr.dest.value + " = caesar_range_init3(" + 
                            call_params[start_idx] + ", " + call_params[start_idx+1] + ", " + call_params[start_idx+2] + ");");
                    call_params.erase(call_params.end() - 3, call_params.end());
                } else if (num_params >= 2) {
                    size_t start_idx = num_params - 2;
                    emitLine("CaesarRange " + instr.dest.value + " = caesar_range_init2(" + 
                            call_params[start_idx] + ", " + call_params[start_idx+1] + ");");
                    call_params.erase(call_params.end() - 2, call_params.end());
                } else if (num_params >= 1) {
                    emitLine("CaesarRange " + instr.dest.value + " = caesar_range_init(" + call_params.back() + ");");
                    call_params.pop_back();
                }
                register_types[instr.dest.value] = "CaesarRange";
            } else if (instr.src1.value == "len") {
                // len() function - check type of argument
                if (!call_params.empty()) {
                    std::string param = call_params.back();  // Take last parameter
                    auto it = register_types.find(param);
                    if (it != register_types.end() && (it->second == "char*" || it->second == "const char*")) {
                        emitLine("int64_t " + instr.dest.value + " = caesar_len_str(" + param + ");");
                    } else {
                        emitLine("int64_t " + instr.dest.value + " = 0;  // TODO: len() for non-string types");
                    }
                    register_types[instr.dest.value] = "int64_t";
                    call_params.pop_back();  // Remove used parameter
                }
            } else {
                // User-defined function call
                std::string func_name = instr.src1.value;
                std::string func_label = "func_" + instr.src1.value;
                
                // Determine how many parameters this function expects (from function definition)
                size_t expected_param_count = call_params.size();  // default to all
                auto params_it = function_params.find(func_label);
                if (params_it != function_params.end()) {
                    expected_param_count = params_it->second.size();
                }
                
                // Only consume the LAST N parameters from call_params (for nested calls)
                size_t params_to_use = std::min(expected_param_count, call_params.size());
                size_t start_idx = call_params.size() - params_to_use;
                
                // Determine actual argument types for monomorphization lookup
                std::vector<std::string> arg_types;
                for (size_t i = 0; i < params_to_use; i++) {
                    std::string param_reg = call_params[start_idx + i];
                    auto type_it = register_types.find(param_reg);
                    std::string param_type = (type_it != register_types.end()) ? type_it->second : "int64_t";
                    arg_types.push_back(param_type);
                }
                
                // Look up monomorphized function name
                auto mono_it = monomorphized_names.find({func_label, arg_types});
                if (mono_it != monomorphized_names.end()) {
                    func_name = mono_it->second;
                } else {
                    // No monomorphized version found: use default name
                    if (c_reserved_words.find(func_name) != c_reserved_words.end()) {
                        func_name = "caesar_" + func_name;
                    }
                }
                
                // Look up return type from instantiation_return_types (per-signature return type)
                auto ret_inst_it = instantiation_return_types.find({func_label, arg_types});
                std::string return_type;
                if (ret_inst_it != instantiation_return_types.end()) {
                    return_type = ret_inst_it->second;
                } else {
                    // Fall back to function_return_types if no instantiation-specific type found
                    auto ret_it = function_return_types.find(func_label);
                    return_type = (ret_it != function_return_types.end()) ? ret_it->second : "int64_t";
                }
                
                std::string args;
                for (size_t i = 0; i < params_to_use; i++) {
                    if (i > 0) args += ", ";
                    args += call_params[start_idx + i];  // Use correct index from end of list
                }
                emitLine(return_type + " " + instr.dest.value + " = " + func_name + "(" + args + ");");
                register_types[instr.dest.value] = return_type;  // Track register type for future uses
                
                // Remove consumed parameters from the end
                call_params.erase(call_params.end() - params_to_use, call_params.end());
            }
            // Don't clear all - nested calls need remaining params
            if (call_params.empty()) {
                call_params.clear();
            }
            break;
        }
            
        case IROpcode::PRINT:
            emitLine("printf(\"%lld\\n\", (long long)" + instr.dest.value + ");");
            break;
            
        case IROpcode::ITER_INIT:
            // Initialize iterator - source should already be a CaesarRange from range() call
            emitLine("CaesarRange " + instr.dest.value + " = " + instr.src1.value + ";");
            register_types[instr.dest.value] = "CaesarRange";
            break;
            
        case IROpcode::ITER_NEXT:
            // Get next value from iterator
            emitLine("int64_t " + instr.dest.value + " = caesar_range_next(&" + instr.src1.value + ");");
            register_types[instr.dest.value] = "int64_t";
            break;
            
        case IROpcode::ITER_DONE:
            // Check if iteration is complete
            emitLine("bool " + instr.dest.value + " = !caesar_range_has_next(&" + instr.src1.value + ");");
            register_types[instr.dest.value] = "bool";
            break;
            
        default:
            emitLine("// " + opcodeToString(instr.opcode) + " (not implemented)");
    }
}

std::string CCodeGenerator::generate(const std::vector<BasicBlock>& blocks) {
    output.str("");
    variable_types.clear();
    register_types.clear();
    function_return_types.clear();  // Clear member variable
    
    // Monomorphization tracking: func_label -> list of unique type signatures
    // Each signature is a vector of param types (e.g., ["int64_t", "const char*"])
    std::unordered_map<std::string, std::vector<std::vector<std::string>>> function_instantiations;
    
    // Use member variable monomorphized_names (don't redeclare!)
    monomorphized_names.clear();  // Clear from previous calls
    
    // Pass 1a: Collect function names and parameters from DECLARE instructions
    std::vector<std::string> function_names;
    function_params.clear();  // Clear member variable before use
    std::unordered_map<std::string, std::string> block_owner;  // block_label -> func_label (or "main")
    
    std::string current_function = "main";
    for (const auto& block : blocks) {
        // Detect function start
        if (block.label.rfind("func_", 0) == 0 && block.label != "func_") {
            function_names.push_back(block.label);
            current_function = block.label;
            
            // Collect parameters from DECLARE instructions
            std::vector<std::string> params;
            for (const auto& instr : block.instructions) {
                if (instr.opcode == IROpcode::DECLARE && instr.dest.type == IROperandType::VARIABLE) {
                    params.push_back(instr.dest.value);
                }
            }
            function_params[block.label] = params;
        } 
        // Detect function end
        else if (block.label.rfind("after_func", 0) == 0) {
            current_function = "main";
        }
        block_owner[block.label] = current_function;
    }
    
    // Pass 1b: Collect parameter types from all call sites (iterative until stable)
    std::unordered_map<std::string, std::vector<std::string>> function_param_types;  // func_name -> param types
    std::unordered_map<std::string, std::string> temp_register_types;  // Reused across iterations
    
    // Iterate until types stabilize (max 10 iterations to prevent infinite loops)
    for (int iteration = 0; iteration < 10; iteration++) {
        bool types_changed = false;
        temp_register_types.clear();  // Reset each iteration
        std::vector<std::string> pending_call_params;
        std::vector<std::string> pending_call_param_types;
        
        // Also track function return types from previous iteration for GET_VAR of function calls
        std::unordered_map<std::string, std::string> temp_function_return_types;
        
        for (const auto& block : blocks) {
            for (const auto& instr : block.instructions) {
                // Track LOAD_CONST to know register types
                if (instr.opcode == IROpcode::LOAD_CONST && instr.dest.type == IROperandType::REGISTER) {
                    if (!instr.src1.value.empty() && instr.src1.value[0] == '"') {
                        temp_register_types[instr.dest.value] = "const char*";
                    } else if (instr.src1.value.find('.') != std::string::npos || 
                               instr.src1.value.find('e') != std::string::npos ||
                               instr.src1.value.find('E') != std::string::npos) {
                        temp_register_types[instr.dest.value] = "double";
                    } else {
                        temp_register_types[instr.dest.value] = "int64_t";
                    }
                }
                
                // Track GET_VAR to propagate parameter types from current iteration
                if (instr.opcode == IROpcode::GET_VAR && instr.dest.type == IROperandType::REGISTER) {
                    std::string var_name = instr.src1.value;
                    // Check if this variable is a parameter with a known type from previous iteration
                    for (const auto& [func_label, param_names] : function_params) {
                        for (size_t i = 0; i < param_names.size(); i++) {
                            if (param_names[i] == var_name && function_param_types.find(func_label) != function_param_types.end()) {
                                const auto& param_types = function_param_types[func_label];
                                if (i < param_types.size()) {
                                    temp_register_types[instr.dest.value] = param_types[i];
                                }
                            }
                        }
                    }
                }
                
                // Track PARAM instructions to collect parameter types
                if (instr.opcode == IROpcode::PARAM) {
                    std::string param_reg = instr.dest.value;
                    auto it = temp_register_types.find(param_reg);
                    std::string param_type = (it != temp_register_types.end()) ? it->second : "int64_t";
                    pending_call_params.push_back(param_reg);
                    pending_call_param_types.push_back(param_type);
                }
                
                // Track CALL to match parameters to functions
                if (instr.opcode == IROpcode::CALL && !pending_call_params.empty()) {
                    std::string func_name = instr.src1.value;
                    for (const auto& fn : function_names) {
                        if (fn == "func_" + func_name) {
                            // Determine how many parameters this function expects
                            auto params_it = function_params.find(fn);
                            size_t expected_param_count = (params_it != function_params.end()) 
                                ? params_it->second.size() 
                                : pending_call_param_types.size();
                            
                            // Only take the LAST N parameters from pending list
                            std::vector<std::string> this_call_types;
                            if (pending_call_param_types.size() >= expected_param_count) {
                                this_call_types.assign(
                                    pending_call_param_types.end() - expected_param_count,
                                    pending_call_param_types.end()
                                );
                                pending_call_params.erase(
                                    pending_call_params.end() - expected_param_count,
                                    pending_call_params.end()
                                );
                                pending_call_param_types.erase(
                                    pending_call_param_types.end() - expected_param_count,
                                    pending_call_param_types.end()
                                );
                            } else {
                                this_call_types = pending_call_param_types;
                                pending_call_params.clear();
                                pending_call_param_types.clear();
                            }
                            
                            // Track this instantiation for monomorphization
                            auto& instantiations = function_instantiations[fn];
                            bool signature_exists = false;
                            for (const auto& sig : instantiations) {
                                if (sig == this_call_types) {
                                    signature_exists = true;
                                    break;
                                }
                            }
                            if (!signature_exists && !this_call_types.empty()) {
                                instantiations.push_back(this_call_types);
                                types_changed = true;
                            }
                            
                            // For backward compatibility: also update function_param_types with merged types
                            if (function_param_types.find(fn) == function_param_types.end()) {
                                function_param_types[fn] = this_call_types;
                                types_changed = true;
                            } else {
                                // Merge types: prefer string/float over int64_t
                                auto& existing_types = function_param_types[fn];
                                for (size_t i = 0; i < this_call_types.size() && i < existing_types.size(); i++) {
                                    if (existing_types[i] == "int64_t" && this_call_types[i] != "int64_t") {
                                        existing_types[i] = this_call_types[i];
                                        types_changed = true;
                                    }
                                }
                            }
                            break;
                        }
                    }
                    
                    // Handle built-in functions
                    if (func_name == "print" || func_name == "len") {
                        if (!pending_call_param_types.empty()) {
                            pending_call_params.pop_back();
                            pending_call_param_types.pop_back();
                        }
                    } else if (func_name == "range") {
                        size_t range_params = std::min<size_t>(3, pending_call_param_types.size());
                        if (range_params > 0) {
                            pending_call_params.erase(pending_call_params.end() - range_params, pending_call_params.end());
                            pending_call_param_types.erase(pending_call_param_types.end() - range_params, pending_call_param_types.end());
                        }
                    }
                }
            }
        }
        
        // If no types changed this iteration, we've reached stability
        if (!types_changed) {
            break;
        }
    }
    
    // Pass 1c: Infer parameter types from function body usage
    // This handles cases where parameters are used with built-in functions (len),
    // in comparisons with literals, or in arithmetic operations
    for (const auto& func_entry : function_params) {
        const std::string& func_label = func_entry.first;
        const std::vector<std::string>& params = func_entry.second;
        
        if (params.empty()) continue;
        
        // Find the function's block
        for (const auto& block : blocks) {
            if (block.label != func_label) continue;
            
            // Track what we learn about each parameter
            std::unordered_map<std::string, std::string> param_inferred_types;
            std::unordered_map<std::string, std::string> local_reg_types;
            std::vector<std::string> local_call_params;
            
            for (const auto& instr : block.instructions) {
                // Track LOAD_CONST for type inference
                if (instr.opcode == IROpcode::LOAD_CONST) {
                    if (!instr.src1.value.empty() && instr.src1.value[0] == '"') {
                        local_reg_types[instr.dest.value] = "const char*";
                    } else if (instr.src1.value.find('.') != std::string::npos || 
                               instr.src1.value.find('e') != std::string::npos ||
                               instr.src1.value.find('E') != std::string::npos) {
                        local_reg_types[instr.dest.value] = "double";
                    } else {
                        local_reg_types[instr.dest.value] = "int64_t";
                    }
                }
                
                // Track GET_VAR - parameter loaded into register
                if (instr.opcode == IROpcode::GET_VAR) {
                    const std::string& var_name = instr.src1.value;
                    bool is_param = false;
                    for (const auto& p : params) {
                        if (p == var_name) {
                            is_param = true;
                            break;
                        }
                    }
                    if (is_param) {
                        // This register holds a parameter value
                        local_reg_types[instr.dest.value] = "PARAM:" + var_name;
                    }
                }
                
                // Detect len() calls - parameter must be string
                if (instr.opcode == IROpcode::PARAM) {
                    local_call_params.push_back(instr.dest.value);
                }
                
                if (instr.opcode == IROpcode::CALL && instr.src1.value == "len") {
                    if (!local_call_params.empty()) {
                        std::string param_reg = local_call_params.back();
                        auto it = local_reg_types.find(param_reg);
                        if (it != local_reg_types.end() && it->second.rfind("PARAM:", 0) == 0) {
                            std::string param_name = it->second.substr(6);  // Skip "PARAM:"
                            param_inferred_types[param_name] = "const char*";
                        }
                        local_call_params.pop_back();
                    }
                }
                
                // Detect arithmetic/comparison operations with int literals
                if (instr.opcode == IROpcode::ADD || instr.opcode == IROpcode::SUB ||
                    instr.opcode == IROpcode::MUL || instr.opcode == IROpcode::DIV ||
                    instr.opcode == IROpcode::EQ || instr.opcode == IROpcode::NE ||
                    instr.opcode == IROpcode::LT || instr.opcode == IROpcode::LE ||
                    instr.opcode == IROpcode::GT || instr.opcode == IROpcode::GE) {
                    
                    // Check if either operand is a parameter
                    for (const std::string& reg : {instr.src1.value, instr.src2.value}) {
                        auto it = local_reg_types.find(reg);
                        if (it != local_reg_types.end() && it->second.rfind("PARAM:", 0) == 0) {
                            std::string param_name = it->second.substr(6);
                            
                            // Check if the other operand gives us type info
                            std::string other_reg = (reg == instr.src1.value) ? instr.src2.value : instr.src1.value;
                            auto other_it = local_reg_types.find(other_reg);
                            
                            if (other_it != local_reg_types.end()) {
                                if (other_it->second == "int64_t" && param_inferred_types.find(param_name) == param_inferred_types.end()) {
                                    param_inferred_types[param_name] = "int64_t";
                                } else if (other_it->second == "double") {
                                    param_inferred_types[param_name] = "double";
                                }
                            }
                        }
                    }
                }
                
                // Detect RETURN - if returning a parameter directly
                if (instr.opcode == IROpcode::RETURN && instr.dest.type == IROperandType::REGISTER) {
                    auto it = local_reg_types.find(instr.dest.value);
                    if (it != local_reg_types.end() && it->second.rfind("PARAM:", 0) == 0) {
                        std::string param_name = it->second.substr(6);
                        // If we know the return type from call sites, use it for parameter
                        auto ret_it = function_return_types.find(func_label);
                        if (ret_it != function_return_types.end() && ret_it->second != "int64_t") {
                            param_inferred_types[param_name] = ret_it->second;
                        }
                    }
                }
            }
            
            // Apply inferred types to function_param_types
            if (!param_inferred_types.empty()) {
                auto& param_types = function_param_types[func_label];
                if (param_types.empty()) {
                    param_types.resize(params.size(), "int64_t");
                }
                
                for (size_t i = 0; i < params.size(); i++) {
                    auto it = param_inferred_types.find(params[i]);
                    if (it != param_inferred_types.end()) {
                        // Upgrade type if we found something more specific
                        if (param_types[i] == "int64_t" || param_types.size() <= i) {
                            if (i < param_types.size()) {
                                param_types[i] = it->second;
                            }
                        }
                    }
                }
            }
            
            break;  // Found the function block, no need to continue
        }
    }
    
    // Pass 1d: Generate monomorphized function names
    // For each function with multiple instantiations, create unique C function names
    for (const auto& entry : function_instantiations) {
        const std::string& func_label = entry.first;
        const std::vector<std::vector<std::string>>& instantiations = entry.second;
        
        // Extract base function name (remove "func_" prefix)
        std::string base_name = (func_label.length() > 5) ? func_label.substr(5) : func_label;
        if (base_name.empty()) {
            continue;  // Skip functions with empty names (shouldn't happen, but defensive)
        }
        
        for (const auto& signature : instantiations) {
            // Generate suffix from type signature
            std::string suffix;
            for (const std::string& type : signature) {
                if (!suffix.empty()) suffix += "_";
                
                if (type == "int64_t") {
                    suffix += "int";
                } else if (type == "const char*" || type == "char*") {
                    suffix += "str";
                } else if (type == "double") {
                    suffix += "float";
                } else if (type == "bool") {
                    suffix += "bool";
                } else {
                    suffix += "any";
                }
            }
            
            // Generate monomorphized name
            std::string mono_name;
            // Only monomorphize if: (1) multiple instantiations exist AND (2) function has parameters
            if (instantiations.size() == 1 || signature.empty()) {
                // Single instantiation or no parameters: use base name (no suffix)
                mono_name = base_name;
            } else {
                // Multiple instantiations with parameters: append type suffix
                mono_name = base_name + "_" + suffix;
            }
            
            // Handle C reserved words
            if (c_reserved_words.find(base_name) != c_reserved_words.end()) {
                mono_name = "caesar_" + mono_name;
            }
            
            monomorphized_names[{func_label, signature}] = mono_name;
        }
    }
    
    // Pass 1e: Infer return types per instantiation
    // For functions that return a parameter, the return type matches that parameter's type
    instantiation_return_types.clear();  // Use member variable
    
    for (const auto& entry : function_instantiations) {
        const std::string& func_label = entry.first;
        const std::vector<std::vector<std::string>>& instantiations = entry.second;
        
        // Find which parameter (if any) is returned by this function
        int returned_param_index = -1;
        for (const auto& block : blocks) {
            if (block.label != func_label) continue;
            
            std::unordered_map<std::string, int> param_indices;
            auto& params = function_params[func_label];
            for (size_t i = 0; i < params.size(); i++) {
                param_indices[params[i]] = i;
            }
            
            // Look for RETURN instruction
            for (const auto& instr : block.instructions) {
                if (instr.opcode == IROpcode::RETURN && instr.dest.type == IROperandType::REGISTER) {
                    // Check if this register came from a GET_VAR of a parameter
                    for (const auto& instr2 : block.instructions) {
                        if (instr2.opcode == IROpcode::GET_VAR && instr2.dest.value == instr.dest.value) {
                            auto it = param_indices.find(instr2.src1.value);
                            if (it != param_indices.end()) {
                                returned_param_index = it->second;
                                break;
                            }
                        }
                    }
                }
            }
            break;
        }
        
        // Set return type for each instantiation
        for (const auto& signature : instantiations) {
            std::string return_type = "int64_t";  // default
            if (returned_param_index >= 0 && returned_param_index < (int)signature.size()) {
                return_type = signature[returned_param_index];
            }
            instantiation_return_types[{func_label, signature}] = return_type;
        }
    }
    
    // Pass 2: Infer return types now that we know parameter types
    std::unordered_map<std::string, std::string> local_function_return_types;
    temp_register_types.clear();  // Reset for second pass
    current_function = "main";
    
    for (const auto& block : blocks) {
        // Track which function we're in
        auto owner_it = block_owner.find(block.label);
        if (owner_it != block_owner.end()) {
            current_function = owner_it->second;
        }
        
        // If this is a function block, register its parameter types in temp_register_types AND variable_types
        if (block.label.rfind("func_", 0) == 0 && block.label != "func_main") {
            auto param_it = function_param_types.find(block.label);
            if (param_it != function_param_types.end()) {
                auto& params = function_params[block.label];
                auto& param_types = param_it->second;
                for (size_t i = 0; i < params.size() && i < param_types.size(); i++) {
                    temp_register_types[params[i]] = param_types[i];
                    variable_types[params[i]] = param_types[i];  // Also populate variable_types for GET_VAR tracking
                }
            }
        }
        
        for (const auto& instr : block.instructions) {
            // Track register types from LOAD_CONST
            if (instr.opcode == IROpcode::LOAD_CONST && instr.dest.type == IROperandType::REGISTER) {
                if (!instr.src1.value.empty() && instr.src1.value[0] == '"') {
                    temp_register_types[instr.dest.value] = "const char*";
                } else if (instr.src1.value.find('.') != std::string::npos || 
                           instr.src1.value.find('e') != std::string::npos ||
                           instr.src1.value.find('E') != std::string::npos) {
                    temp_register_types[instr.dest.value] = "double";
                } else {
                    temp_register_types[instr.dest.value] = "int64_t";
                }
            }
            // Track GET_VAR to propagate variable types to registers
            if (instr.opcode == IROpcode::GET_VAR && instr.src1.type == IROperandType::VARIABLE) {
                auto vit = variable_types.find(instr.src1.value);
                if (vit != variable_types.end()) {
                    temp_register_types[instr.dest.value] = vit->second;
                } else {
                    variable_types[instr.src1.value] = "int64_t";  // Default
                }
            }
            // Track variable types from SET_VAR
            if (instr.opcode == IROpcode::SET_VAR && instr.dest.type == IROperandType::VARIABLE) {
                auto it = temp_register_types.find(instr.src1.value);
                if (it != temp_register_types.end()) {
                    variable_types[instr.dest.value] = it->second;
                } else {
                    variable_types[instr.dest.value] = "int64_t";  // Default
                }
            }
            // Track arithmetic operations - determine result types
            if (instr.opcode == IROpcode::DIV) {
                // Division always returns double
                temp_register_types[instr.dest.value] = "double";
            } else if (instr.opcode == IROpcode::ADD || instr.opcode == IROpcode::SUB || 
                       instr.opcode == IROpcode::MUL || instr.opcode == IROpcode::MOD) {
                // Check operand types - if either is double, result is double
                std::string type1 = "int64_t";
                std::string type2 = "int64_t";
                
                if (instr.src1.type == IROperandType::REGISTER) {
                    auto it = temp_register_types.find(instr.src1.value);
                    if (it != temp_register_types.end()) type1 = it->second;
                }
                if (instr.src2.type == IROperandType::REGISTER) {
                    auto it = temp_register_types.find(instr.src2.value);
                    if (it != temp_register_types.end()) type2 = it->second;
                }
                
                // Promote to double if either operand is double
                if (type1 == "double" || type2 == "double") {
                    temp_register_types[instr.dest.value] = "double";
                } else {
                    temp_register_types[instr.dest.value] = "int64_t";
                }
            } else if (instr.opcode == IROpcode::NEG) {
                // Negation preserves operand type
                if (instr.src1.type == IROperandType::REGISTER) {
                    auto it = temp_register_types.find(instr.src1.value);
                    if (it != temp_register_types.end()) {
                        temp_register_types[instr.dest.value] = it->second;
                    }
                }
            }
            // Track RETURN instructions - determine return type (parameter types already collected in Pass 1b)
            if (instr.opcode == IROpcode::RETURN && current_function != "main" && 
                instr.dest.type != IROperandType::NONE) {
                // Get the type of the return value
                std::string return_type = "int64_t";  // default
                if (instr.dest.type == IROperandType::REGISTER || instr.dest.type == IROperandType::VARIABLE) {
                    auto it = temp_register_types.find(instr.dest.value);
                    if (it != temp_register_types.end()) {
                        return_type = it->second;
                    } else {
                        // Check if it's a parameter of this function
                        auto param_types_it = function_param_types.find(current_function);
                        auto params_it = function_params.find(current_function);
                        if (param_types_it != function_param_types.end() && params_it != function_params.end()) {
                            auto& params = params_it->second;
                            auto& param_types = param_types_it->second;
                            for (size_t i = 0; i < params.size() && i < param_types.size(); i++) {
                                if (params[i] == instr.dest.value) {
                                    return_type = param_types[i];
                                    break;
                                }
                            }
                        }
                    }
                } else if (instr.dest.type == IROperandType::CONSTANT) {
                    // Check if constant is a float or string
                    if (!instr.dest.value.empty() && instr.dest.value[0] == '"') {
                        return_type = "const char*";
                    } else if (instr.dest.value.find('.') != std::string::npos || 
                               instr.dest.value.find('e') != std::string::npos ||
                               instr.dest.value.find('E') != std::string::npos) {
                        return_type = "double";
                    }
                }
                
                // Update function return type (promote to double if any return is double)
                auto ret_it = local_function_return_types.find(current_function);
                if (ret_it == local_function_return_types.end()) {
                    local_function_return_types[current_function] = return_type;
                } else if (ret_it->second == "int64_t" && return_type == "double") {
                    // Promote to double if any return path returns double
                    local_function_return_types[current_function] = "double";
                } else if (ret_it->second == "double" || return_type == "double") {
                    // Keep as double if either is double
                    local_function_return_types[current_function] = "double";
                } else if (ret_it->second == "const char*" || return_type == "const char*") {
                    // Keep as const char* if either is string
                    local_function_return_types[current_function] = "const char*";
                }
            }
        }
    }
    
    // Copy local tracking to member variable for use in emitInstruction
    function_return_types = local_function_return_types;
    
    output << "// Caesar C Code\n";
    output << "// Generated by Caesar Compiler v1.5.1\n\n";
    output << "#include \"caesar/caesar_runtime.h\"\n\n";
    
    // Generate forward declarations for user functions (including monomorphized versions)
    if (!function_names.empty()) {
        output << "// Forward declarations\n";
        for (const auto& func_label : function_names) {
            auto inst_it = function_instantiations.find(func_label);
            
            if (inst_it != function_instantiations.end() && !inst_it->second.empty()) {
                // Generate declaration for each monomorphized version
                for (const auto& signature : inst_it->second) {
                    // Try to get monomorphized name; skip if not found or empty
                    auto mono_it = monomorphized_names.find({func_label, signature});
                    std::string mono_name;
                    if (mono_it != monomorphized_names.end() && !mono_it->second.empty()) {
                        mono_name = mono_it->second;
                    } else {
                        mono_name = safe_function_name(func_label);
                    }
                    
                    auto& params = function_params[func_label];
                    
                    // Get return type - use instantiation-specific return type
                    auto ret_inst_it = instantiation_return_types.find({func_label, signature});
                    std::string return_type = "int64_t";
                    if (ret_inst_it != instantiation_return_types.end()) {
                        return_type = ret_inst_it->second;
                    } else {
                        auto ret_it = local_function_return_types.find(func_label);
                        if (ret_it != local_function_return_types.end()) {
                            return_type = ret_it->second;
                        }
                    }
                    
                    output << return_type << " " << mono_name << "(";
                    for (size_t i = 0; i < params.size(); i++) {
                        if (i > 0) output << ", ";
                        std::string param_type = (i < signature.size()) ? signature[i] : "int64_t";
                        output << param_type << " " << params[i];
                    }
                    output << ");\n";
                }
            } else {
                // No instantiations tracked: use default signature
                std::string func_name = safe_function_name(func_label);
                auto& params = function_params[func_label];
                auto& param_types = function_param_types[func_label];
                
                auto ret_it = local_function_return_types.find(func_label);
                std::string return_type = (ret_it != local_function_return_types.end()) ? ret_it->second : "int64_t";
                
                output << return_type << " " << func_name << "(";
                for (size_t i = 0; i < params.size(); i++) {
                    if (i > 0) output << ", ";
                    std::string param_type = (i < param_types.size()) ? param_types[i] : "int64_t";
                    output << param_type << " " << params[i];
                }
                output << ");\n";
            }
        }
        output << "\n";
    }
    
    // Generate user-defined functions (including all monomorphized versions)
    for (const auto& func_label : function_names) {
        auto& params = function_params[func_label];
        
        // Get all instantiations for this function
        auto inst_it = function_instantiations.find(func_label);
        std::vector<std::vector<std::string>> signatures_to_generate;
        
        if (inst_it != function_instantiations.end() && !inst_it->second.empty()) {
            signatures_to_generate = inst_it->second;
        } else {
            // No instantiations: use default signature
            signatures_to_generate.push_back(function_param_types[func_label]);
        }
        
        // Generate a function for each unique signature
        for (const auto& signature : signatures_to_generate) {
            std::string func_name;
            std::string return_type;
            
            if (inst_it != function_instantiations.end()) {
                // Try to get monomorphized name; fall back to safe_function_name if not found
                auto mono_it = monomorphized_names.find({func_label, signature});
                if (mono_it != monomorphized_names.end() && !mono_it->second.empty()) {
                    func_name = mono_it->second;
                } else {
                    func_name = safe_function_name(func_label);
                }
                
                // Use instantiation-specific return type
                auto ret_inst_it = instantiation_return_types.find({func_label, signature});
                if (ret_inst_it != instantiation_return_types.end()) {
                    return_type = ret_inst_it->second;
                } else {
                    auto ret_it = local_function_return_types.find(func_label);
                    return_type = (ret_it != local_function_return_types.end()) ? ret_it->second : "int64_t";
                }
            } else {
                func_name = safe_function_name(func_label);
                auto ret_it = local_function_return_types.find(func_label);
                return_type = (ret_it != local_function_return_types.end()) ? ret_it->second : "int64_t";
            }
            
            output << return_type << " " << func_name << "(";
            for (size_t i = 0; i < params.size(); i++) {
                if (i > 0) output << ", ";
                std::string param_type = (i < signature.size()) ? signature[i] : "int64_t";
                output << param_type << " " << params[i];
            }
            output << ") {\n";
            
            indent_level = 1;
            
            // Register parameter types in variable_types map for this function's scope
            for (size_t i = 0; i < params.size(); i++) {
                std::string param_type = (i < signature.size()) ? signature[i] : "int64_t";
                variable_types[params[i]] = param_type;
                register_types[params[i]] = param_type;  // Also add to register_types for consistency
            }
        
        // Collect local variables for this function (non-param variables used in function)
        std::unordered_set<std::string> func_local_vars;
        for (const auto& block : blocks) {
            // Check if block belongs to this function
            auto owner_it = block_owner.find(block.label);
            if (owner_it != block_owner.end() && owner_it->second == func_label) {
                for (const auto& instr : block.instructions) {
                    if (instr.opcode == IROpcode::SET_VAR && instr.dest.type == IROperandType::VARIABLE) {
                        std::string var_name = instr.dest.value;
                        // Check if it's not a parameter
                        bool is_param = false;
                        for (const auto& param : params) {
                            if (param == var_name) {
                                is_param = true;
                                break;
                            }
                        }
                        if (!is_param) {
                            func_local_vars.insert(var_name);
                        }
                    }
                }
            }
        }
        
        // Declare local variables
        for (const auto& var : func_local_vars) {
            auto it = variable_types.find(var);
            std::string var_type = (it != variable_types.end()) ? it->second : "int64_t";
            emitLine(var_type + " " + var + " = 0;");
        }
        if (!func_local_vars.empty()) output << "\n";
        
        // Emit all blocks belonging to this function
        for (const auto& block : blocks) {
            // Check if this block belongs to this function
            auto owner_it = block_owner.find(block.label);
            if (owner_it != block_owner.end() && owner_it->second == func_label) {
                // Emit label if not the function start
                if (block.label != func_label && !block.label.empty()) {
                    indent_level = 0;
                    output << block.label << ":\n";
                    indent_level = 1;
                }
                
                // Process instructions, skipping DECLARE (already in signature)
                for (const auto& instr : block.instructions) {
                    if (instr.opcode != IROpcode::DECLARE) {
                        emitInstruction(instr);
                    }
                }
            }
        }
        
            indent_level = 0;
            output << "}\n\n";
        }  // end for each signature
    }  // end for each function
    
    // Generate main function
    output << "int main() {\n";
    indent_level = 1;
    
    // Declare all non-parameter user variables at the top
    std::unordered_set<std::string> param_names;
    for (const auto& pair : function_params) {
        for (const auto& param : pair.second) {
            param_names.insert(param);
        }
    }
    
    bool has_main_vars = false;
    for (const auto& var : variable_types) {
        if (param_names.find(var.first) == param_names.end()) {
            if (!has_main_vars) {
                emitLine("// User variables");
                has_main_vars = true;
            }
            emitLine(var.second + " " + var.first + " = 0;");
        }
    }
    if (has_main_vars) output << "\n";
    
    // Process main code (blocks owned by "main")
    for (const auto& block : blocks) {
        // Only include blocks owned by main
        auto owner_it = block_owner.find(block.label);
        if (owner_it == block_owner.end() || owner_it->second != "main") {
            continue;
        }
        
        if (!block.label.empty() && block.label != "entry" && !block.label.rfind("after_func", 0) == 0) {
            indent_level = 0;
            output << block.label << ":\n";
            indent_level = 1;
        }
        
        for (const auto& instr : block.instructions) {
            emitInstruction(instr);
        }
    }
    
    indent_level = 1;
    emitLine("return 0;");
    indent_level = 0;
    output << "}\n";
    
    return output.str();
}

