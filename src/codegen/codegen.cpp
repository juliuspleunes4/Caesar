// C reserved keywords that cannot be used as function names
static const std::unordered_set<std::string> c_reserved_words = {
    "auto", "break", "case", "char", "const", "continue", "default", "do",
    "double", "else", "enum", "extern", "float", "for", "goto", "if",
    "int", "long", "register", "return", "short", "signed", "sizeof", "static",
    "struct", "switch", "typedef", "union", "unsigned", "void", "volatile", "while",
    "bool", "true", "false"  // Also C++ keywords commonly used
};

// Helper: Convert Caesar function name to safe C function name
static std::string safe_function_name(const std::string& caesar_name) {
    // Extract the actual name from "func_NAME"
    std::string name = (caesar_name.length() > 5) ? caesar_name.substr(5) : caesar_name;
    
    // Defensive: if name is empty after extraction, return a placeholder
    if (name.empty()) {
        return "anonymous_func";
    }
    
    // Check if it's a reserved word
    if (c_reserved_words.find(name) != c_reserved_words.end()) {
        return "caesar_" + name;
    }
    return name;
}

// ============================================================================
// Bytecode Generator
// ============================================================================

void BytecodeGenerator::emitByte(uint8_t byte) {
    output << std::hex << std::setw(2) << std::setfill('0') << (int)byte << " ";
}

void BytecodeGenerator::emitOpcode(const std::string& opcode) {
    output << opcode << " ";
}

void BytecodeGenerator::emitOperand(const IROperand& operand) {
    output << operand.toString() << " ";
}

std::string BytecodeGenerator::generate(const std::vector<BasicBlock>& blocks) {
    output.str("");
    output << "; Caesar Bytecode\n";
    output << "; Generated by Caesar Compiler v1.5.1\n\n";
    
    for (const auto& block : blocks) {
        if (!block.label.empty()) {
            output << block.label << ":\n";
            label_positions[block.label] = stack_size;
        }
        
        for (const auto& instr : block.instructions) {
            output << "  " << opcodeToString(instr.opcode);
            
            if (instr.dest.type != IROperandType::NONE) {
                output << " " << instr.dest.toString();
            }
            if (instr.src1.type != IROperandType::NONE) {
                output << ", " << instr.src1.toString();
            }
            if (instr.src2.type != IROperandType::NONE) {
                output << ", " << instr.src2.toString();
            }
            
            output << "\n";
        }
    }
    
    return output.str();
}

